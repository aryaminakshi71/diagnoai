/**
 * Reports Router
 *
 * Generates PDF laboratory reports for human and veterinary patients.
 */

import { z } from 'zod'
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib'
import { eq } from 'drizzle-orm'
import { orgAuthed, getDb, schema } from '../procedures'

const testResultSchema = z.object({
  name: z.string(),
  result: z.string(),
  unit: z.string().optional(),
  referenceRange: z.string().optional(),
  flag: z.enum(['normal', 'high', 'low']).optional(),
})

const reportSchema = z.object({
  labName: z.string().default('DiagnoAI'),
  labAddress: z.string().optional(),
  labType: z.enum(['human', 'veterinary']).default('human'),
  patientName: z.string(),
  patientAge: z.string().optional(),
  patientSex: z.string().optional(),
  species: z.string().optional(),
  ownerName: z.string().optional(),
  sampleId: z.string().optional(),
  collectedAt: z.string().optional(),
  reportedAt: z.string().optional(),
  tests: z.array(testResultSchema),
  comments: z.string().optional(),
})

export const reportsRouter = {
  generate: orgAuthed
    .route({
      method: 'POST',
      path: '/reports/generate',
      summary: 'Generate a PDF laboratory report',
      tags: ['Reports'],
    })
    .input(reportSchema)
    .output(z.object({ pdfBase64: z.string(), fileName: z.string() }))
    .handler(async ({ context, input }) => {
      const db = getDb(context)
      const [branding] = await db
        .select()
        .from(schema.whiteLabelSettings)
        .where(eq(schema.whiteLabelSettings.organizationId, context.organization.id))
        .limit(1)
      const labName = branding?.brandName ?? input.labName
      const brandColor = branding?.primaryColor ?? '#6366f1'
      const hex = brandColor.replace('#', '')
      const brandRgb = rgb(
        parseInt(hex.slice(0, 2), 16) / 255,
        parseInt(hex.slice(2, 4), 16) / 255,
        parseInt(hex.slice(4, 6), 16) / 255,
      )

      const pdf = await PDFDocument.create()
      const page = pdf.addPage([595, 842]) // A4
      const font = await pdf.embedFont(StandardFonts.Helvetica)
      const bold = await pdf.embedFont(StandardFonts.HelveticaBold)

      let y = 800
      const draw = (text: string, size = 10, isBold = false, x = 40) => {
        page.drawText(text, {
          x,
          y,
          size,
          font: isBold ? bold : font,
          color: rgb(0, 0, 0),
        })
        y -= size + 6
      }

      page.drawText(labName, { x: 40, y, size: 18, font: bold, color: brandRgb })
      y -= 24
      if (input.labAddress) draw(input.labAddress, 9)
      y -= 8
      draw('LABORATORY REPORT', 14, true)
      y -= 4

      draw(`Patient: ${input.patientName}`)
      if (input.patientAge) draw(`Age: ${input.patientAge}`)
      if (input.patientSex) draw(`Sex: ${input.patientSex}`)
      if (input.labType === 'veterinary' && input.species)
        draw(`Species: ${input.species}`)
      if (input.ownerName) draw(`Owner: ${input.ownerName}`)
      if (input.sampleId) draw(`Sample ID: ${input.sampleId}`)
      if (input.collectedAt) draw(`Collected: ${input.collectedAt}`)
      if (input.reportedAt) draw(`Reported: ${input.reportedAt}`)
      y -= 10

      draw('Test', 10, true, 40)
      draw('Result', 10, true, 260)
      draw('Reference', 10, true, 380)
      y += 16
      page.drawLine({
        start: { x: 40, y: y + 4 },
        end: { x: 555, y: y + 4 },
        thickness: 0.5,
        color: rgb(0.6, 0.6, 0.6),
      })
      y -= 4

      for (const t of input.tests) {
        const flag =
          t.flag && t.flag !== 'normal' ? `  [${t.flag.toUpperCase()}]` : ''
        page.drawText(`${t.name}${flag}`, {
          x: 40,
          y,
          size: 10,
          font,
          color: rgb(0, 0, 0),
        })
        page.drawText(`${t.result}${t.unit ? ' ' + t.unit : ''}`, {
          x: 260,
          y,
          size: 10,
          font,
          color: rgb(0, 0, 0),
        })
        page.drawText(t.referenceRange || '-', {
          x: 380,
          y,
          size: 10,
          font,
          color: rgb(0, 0, 0),
        })
        y -= 16
      }

      if (input.comments) {
        y -= 10
        draw('Comments:', 10, true)
        draw(input.comments, 9)
      }

      y = 60
      page.drawText(
        `This report is generated by ${labName}. Results should be interpreted by a qualified professional.`,
        { x: 40, y, size: 7, font, color: rgb(0.4, 0.4, 0.4) },
      )

      const bytes = await pdf.save()
      const base64 = Buffer.from(bytes).toString('base64')
      return {
        pdfBase64: base64,
        fileName: `report-${input.sampleId || Date.now()}.pdf`,
      }
    }),
}
